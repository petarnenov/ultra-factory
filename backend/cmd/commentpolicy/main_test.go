package main

import (
	"strings"
	"testing"
)

func TestCommentBoundaries(t *testing.T) {
	cases := []struct {
		name       string
		source     string
		wantLines  int
		wantLong   int
		wantBlocks int
	}{
		{"two adjacent comments", "// first\n// second\npackage p", 2, 0, 0},
		{"three adjacent comments", "// first\n// second\n// third\npackage p", 3, 0, 1},
		{"adjacent block comments", "/* first */\n/* second */\n/* third */\npackage p", 3, 0, 1},
		{"two line block", "/* first\n * second */\npackage p", 2, 0, 0},
		{"three line block", "/* first\n * second\n * third */\npackage p", 3, 0, 1},
		{"inline comment", "package p // inline\n", 1, 0, 0},
		{"comment-like string", "package p\nvar s = `// string text`\n", 0, 0, 0},
		{"80 column line", "// " + strings.Repeat("x", 77) + "\npackage p", 1, 0, 0},
		{"81 column line", "// " + strings.Repeat("x", 78) + "\npackage p", 1, 1, 0},
		{"blank line separates comments", "// first\n\n// second\n// third\npackage p", 3, 0, 0},
		{"directive remains exempt", "//go:build " + strings.Repeat("x", 90) + "\n// ordinary comment\npackage p", 1, 0, 0},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			lines, long, blocks := 0, 0, 0
			comments, err := analyze([]byte(tc.source))
			if err != nil {
				t.Fatal(err)
			}
			for _, item := range comments {
				lines += item.Lines
				long += item.Long
				if item.Lines > 2 {
					blocks++
				}
			}
			if lines != tc.wantLines || long != tc.wantLong || blocks != tc.wantBlocks {
				t.Fatalf("got lines=%d long=%d blocks=%d; want lines=%d long=%d blocks=%d", lines, long, blocks, tc.wantLines, tc.wantLong, tc.wantBlocks)
			}
		})
	}
}

func TestGeneratedAndLicenseCommentExclusions(t *testing.T) {
	generated := []byte("/* Copyright holder */\n// Code generated by tool. DO NOT EDIT.\npackage p\n")
	comments, err := analyze(generated)
	if err != nil {
		t.Fatal(err)
	}
	if len(comments) != 0 {
		t.Fatalf("generated source comments = %#v, want none", comments)
	}

	license := []byte("// Copyright holder\n// Licensed for use\npackage p\n")
	comments, err = analyze(license)
	if err != nil {
		t.Fatal(err)
	}
	if len(comments) != 0 {
		t.Fatalf("license comments = %#v, want none", comments)
	}

	mention := []byte("// This note mentions SPDX-License-Identifier: only.\npackage p\n")
	comments, err = analyze(mention)
	if err != nil {
		t.Fatal(err)
	}
	if len(comments) != 1 {
		t.Fatalf("ordinary comment count = %d, want 1", len(comments))
	}
}
